// ============================================================
// SUBJECT DETECTION
// ============================================================

function detectSubject(question) {

    const text = question.toLowerCase();

    let accountingScore = 0;
    let economicsScore = 0;
    let mathematicsScore = 0;


    accountingKeywords.forEach(keyword => {

        if (text.includes(keyword)) {
            accountingScore++;
        }

    });


    economicsKeywords.forEach(keyword => {

        if (text.includes(keyword)) {
            economicsScore++;
        }

    });


    mathematicsKeywords.forEach(keyword => {

        if (text.includes(keyword)) {
            mathematicsScore++;
        }

    });


    const scores = {
        Accounting: accountingScore,
        Economics: economicsScore,
        Mathematics: mathematicsScore
    };


    const highestScore = Math.max(
        accountingScore,
        economicsScore,
        mathematicsScore
    );


    if (highestScore === 0) {
        return null;
    }


    for (const subject in scores) {

        if (scores[subject] === highestScore) {
            return subject;
        }

    }

    return null;
}


// ============================================================
// ECONOMICS SEARCH
// ============================================================

function searchEconomics(question) {

    const text = question.toLowerCase();

    const words = text.split(/\s+/);

    let bestMatch = null;
    let bestScore = 0;


    economicsKnowledge.forEach(entry => {

        let score = 0;


        entry.keywords.forEach(keyword => {

            if (text.includes(keyword.toLowerCase())) {
                score += 3;
            }

        });


        entry.topic
            .toLowerCase()
            .split(/\s+/)
            .forEach(word => {

                if (words.includes(word)) {
                    score += 1;
                }

            });


        if (score > bestScore) {

            bestScore = score;
            bestMatch = entry;

        }

    });


    if (!bestMatch || bestScore === 0) {
        return null;
    }


    return bestMatch;
}


