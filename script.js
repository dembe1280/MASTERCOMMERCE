function createMessage(text, sender, subject = null) {

    const message = document.createElement("div");

    message.className = `message ${sender}`;


    if (subject) {

        const badge = document.createElement("div");

        badge.className = "subject-badge";

        badge.textContent = subject;

        message.appendChild(badge);

    }


    const content = document.createElement("div");

    content.className = "message-content";

    content.textContent = text;

    message.appendChild(content);


    return message;
}


// ============================================================
// ANSWER QUESTION
// ============================================================

function answerQuestion(question) {

    const cleanedQuestion = question.trim();


    if (!cleanedQuestion) {
        return;
    }


    // Developer questions
    if (isDeveloperQuestion(cleanedQuestion)) {

        const answer = developerAnswer();

        chatMessages.appendChild(
            createMessage(answer, "assistant")
        );

        return;
    }


    // Detect subject
    const subject = detectSubject(cleanedQuestion);


    // Economics
    if (subject === "Economics") {

        const result = searchEconomics(cleanedQuestion);


        if (result) {

            chatMessages.appendChild(
                createMessage(
                    result.information,
                    "assistant",
                    "Economics"
                )
            );

        } else {

            chatMessages.appendChild(
                createMessage(
                    "I understand that this is an Economics question, but I do not have enough information about this topic yet. Please add the relevant Economics material to my knowledge.",
                    "assistant",
                    "Economics"
                )
            );

        }

        return;
    }


    // Accounting
    if (subject === "Accounting") {

        chatMessages.appendChild(
            createMessage(
                "I can identify this as an Accounting question, but my Accounting knowledge is still being added. Please add your Accounting study material to Mastercommerce.",
                "assistant",
                "Accounting"
            )
        );

        return;
    }


    // Mathematics
    if (subject === "Mathematics") {

        chatMessages.appendChild(
            createMessage(
                "I can identify this as a Mathematics question, but my Mathematics knowledge is still being added. Please add your Mathematics study material to Mastercommerce.",
                "assistant",
                "Mathematics"
            )
        );

        return;
    }


    // Unknown subject
    chatMessages.appendChild(
        createMessage(
            "I'm not sure whether this is Accounting, Economics or Mathematics. Please make your question a little clearer.",
            "assistant"
        )
    );
}


// ============================================================
// SEND MESSAGE
// ============================================================

function sendMessage() {

    const question = chatInput.value.trim();


    if (!question) {
        return;
    }


    // User message
    chatMessages.appendChild(
        createMessage(
            question,
            "user"
        )
    );


    // Clear input
    chatInput.value = "";


    // Answer
    setTimeout(() => {

        answerQuestion(question);

        chatMessages.scrollTop =
            chatMessages.scrollHeight;

    }, 300);

}


