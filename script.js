/* =========================================
   DETECT SUBJECT
========================================= */

function detectSubject(question) {

    const text = question.toLowerCase();

    const scores = {
        Accounting: 0,
        Economics: 0,
        Mathematics: 0
    };

    Object.keys(subjectKeywords).forEach(subject => {

        subjectKeywords[subject].forEach(keyword => {

            if (text.includes(keyword)) {
                scores[subject]++;
            }

        });

    });

    const sorted = Object.entries(scores)
        .sort((a, b) => b[1] - a[1]);

    if (sorted[0][1] === 0) {
        return null;
    }

    if (
        sorted.length > 1 &&
        sorted[0][1] === sorted[1][1]
    ) {
        return null;
    }

    return sorted[0][0];
}


/* =========================================
   SEARCH KNOWLEDGE
========================================= */

function searchKnowledge(question, knowledge) {

    const text = question.toLowerCase();

    let bestMatch = null;
    let bestScore = 0;

    knowledge.forEach(item => {

        let score = 0;

        item.keywords.forEach(keyword => {

            if (text.includes(keyword.toLowerCase())) {

                score += keyword.split(" ").length;

            }

        });

        if (text.includes(item.topic.toLowerCase())) {
            score += 5;
        }

        if (score > bestScore) {

            bestScore = score;
            bestMatch = item;

        }

    });

    return bestMatch;
}


