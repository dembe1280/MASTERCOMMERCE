// ============================================================
// CREATE MESSAGE
// ============================================================

function createMessage(text, sender, subject = null) {

    const message = document.createElement("div");

    message.className =
        `message ${sender}`;


    if (subject) {

        const badge =
            document.createElement("div");

        badge.className =
            "subject-badge";

        badge.textContent =
            subject;

        message.appendChild(badge);

    }


    const content =
        document.createElement("div");

    content.className =
        "message-content";

    content.textContent =
        text;

    message.appendChild(content);


    return message;
}


// ============================================================
// ANSWER QUESTION
// ============================================================

function answerQuestion(question) {

    const cleanedQuestion =
        question.trim();


    if (!cleanedQuestion) {
        return;
    }


    // Greeting
    const greeting =
        greetingAnswer(cleanedQuestion);


    if (greeting) {

        chatMessages.appendChild(
            createMessage(
                greeting,
                "assistant"
            )
        );

        return;
    }


    // Developer
    if (
        isDeveloperQuestion(
            cleanedQuestion
        )
    ) {

        chatMessages.appendChild(
            createMessage(
                developerAnswer(),
                "assistant"
            )
        );

        return;
    }


    // Subject
    const subject =
        detectSubject(
            cleanedQuestion
        );


    // Accounting
    if (subject === "Accounting") {

        const result =
            searchKnowledge(
                cleanedQuestion,
                accountingKnowledge
            );


        if (result) {

            chatMessages.appendChild(
                createMessage(
                    result.information,
                    "assistant",
                    "Accounting"
                )
            );

        } else {

            chatMessages.appendChild(
                createMessage(
                    `I know this is an Accounting question, but I don't have enough information about that specific topic yet.

Try asking me about the accounting equation, assets, liabilities, equity, revenue, expenses, inventory, depreciation, VAT, financial statements, ratios, auditing or IFRS.`,
                    "assistant",
                    "Accounting"
                )
            );

        }

        return;
    }


    // Economics
    if (subject === "Economics") {

        const result =
            searchKnowledge(
                cleanedQuestion,
                economicsKnowledge
            );


        if (result) {

            chatMessages.appendChild(
                createMessage(
                    result.information,
                    "assistant",
                    "Economics"
                )
            );

        } else {

            chatMessages.appendChild(
                createMessage(
                    `I know this is an Economics question, but I don't have enough information about that specific topic yet.

Try asking me about scarcity, opportunity cost, demand, supply, elasticity, inflation, unemployment, GDP, economic growth, fiscal policy or monetary policy.`,
                    "assistant",
                    "Economics"
                )
            );

        }

        return;
    }


    // Mathematics
    if (subject === "Mathematics") {

        chatMessages.appendChild(
            createMessage(
                `I can identify this as a Mathematics question, but the Mathematics knowledge base is still being developed.

You can ask me about equations, algebra, quadratic equations, probability, statistics, functions, graphs, calculus and more as the Mathematics section is added.`,
                "assistant",
                "Mathematics"
            )
        );

        return;
    }


    // Unknown
    chatMessages.appendChild(
        createMessage(
            `I'm not completely sure which subject you're asking about.

Please mention a little more about the question.

For example:

"Explain depreciation in Accounting."

"What is inflation in Economics?"

"Solve this quadratic equation in Mathematics."`,
            "assistant"
        )
    );
}


// ============================================================
// SEND MESSAGE
// ============================================================

function sendMessage() {

    const question =
        chatInput.value.trim();


    if (!question) {
        return;
    }


    chatMessages.appendChild(
        createMessage(
            question,
            "user"
        )
    );


    chatInput.value = "";


    setTimeout(() => {

        answerQuestion(
            question
        );


        chatMessages.scrollTop =
            chatMessages.scrollHeight;

    }, 250);

}


