function isDeveloperQuestion(text) {

    const lower = text.toLowerCase();

    return (
        lower.includes("who made you") ||
        lower.includes("who created you") ||
        lower.includes("who developed you") ||
        lower.includes("who built you") ||
        lower.includes("who made mastercommerce") ||
        lower.includes("who created mastercommerce") ||
        lower.includes("who developed mastercommerce") ||
        lower.includes("who built mastercommerce") ||
        lower.includes("developer") ||
        lower.includes("founder")
    );

}


