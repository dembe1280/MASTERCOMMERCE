/* =====================================================
   ANSWER QUESTION
===================================================== */

function answerQuestion(question) {

    const cleaned =
        question.trim();


    if (!cleaned) {
        return;
    }


    if (isGreeting(cleaned)) {

        createMessage(
            greetingAnswer(),
            "assistant"
        );

        return;
    }


    if (isDeveloperQuestion(cleaned)) {

        createMessage(
            developerAnswer(),
            "assistant"
        );

        return;
    }


    const subject =
        detectSubject(cleaned);


    if (!subject) {

        createMessage(
`I'm not completely sure which subject you mean.

Please make your question a little clearer.

For example:

• "Explain the accounting equation."
• "What causes inflation?"
• "How do I solve a quadratic equation?"`,
            "assistant"
        );

        return;
    }


    let knowledge = null;


    if (subject === "accounting") {
        knowledge =
            searchKnowledge(
                cleaned,
                accountingKnowledge
            );
    }


    if (subject === "economics") {
        knowledge =
            searchKnowledge(
                cleaned,
                economicsKnowledge
            );
    }


    if (subject === "mathematics") {
        knowledge =
            searchKnowledge(
                cleaned,
                mathematicsKnowledge
            );
    }


    if (knowledge) {

        createMessage(
            knowledge.answer,
            "assistant"
        );

        return;
    }


    const fallbacks = {

        accounting:
`I understand that this is an Accounting question, but I don't have a specific explanation for that topic in my current knowledge base.

Try asking about accounting equations, financial statements, inventory, VAT, depreciation, ratios, IFRS, auditing or double-entry accounting.`,

        economics:
`I understand that this is an Economics question, but I don't have a specific explanation for that topic in my current knowledge base.

Try asking about demand, supply, scarcity, opportunity cost, inflation, GDP, unemployment, elasticity, fiscal policy or monetary policy.`,

        mathematics:
`I understand that this is a Mathematics question, but I don't have a specific explanation for that topic in my current knowledge base.

Try asking about algebra, equations, quadratics, functions, sequences, financial mathematics, trigonometry, probability, statistics, differentiation or integration.`
    };


    createMessage(
        fallbacks[subject],
        "assistant"
    );

}


