/* =====================================================
   SUBJECT DETECTION
===================================================== */

function detectSubject(question) {

    const text =
        question.toLowerCase();

    const scores = {
        accounting: 0,
        economics: 0,
        mathematics: 0
    };


    Object.entries(subjectKeywords).forEach(
        ([subject, keywords]) => {

            keywords.forEach(keyword => {

                if (text.includes(keyword)) {
                    scores[subject]++;
                }

            });

        }
    );


    const sorted =
        Object.entries(scores)
            .sort((a, b) => b[1] - a[1]);


    if (sorted[0][1] === 0) {
        return null;
    }


    if (
        sorted[0][1] ===
        sorted[1][1]
    ) {
        return null;
    }


    return sorted[0][0];
}


/* =====================================================
   KNOWLEDGE SEARCH
===================================================== */

function searchKnowledge(question, knowledge) {

    const text =
        question.toLowerCase();

    let bestMatch = null;
    let bestScore = 0;


    knowledge.forEach(item => {

        let score = 0;


        item.keywords.forEach(keyword => {

            if (text.includes(keyword)) {

                score +=
                    keyword.length > 8
                        ? 3
                        : 1;

            }

        });


        const titleWords =
            item.title
                .toLowerCase()
                .split(" ");


        titleWords.forEach(word => {

            if (
                word.length > 3 &&
                text.includes(word)
            ) {
                score++;
            }

        });


        if (score > bestScore) {

            bestScore = score;
            bestMatch = item;

        }

    });


    return bestMatch;
}


