// SUBJECT DETECTION
// ============================================================

function detectSubject(question) {

    const text = question.toLowerCase();

    let accountingScore = 0;
    let economicsScore = 0;
    let mathematicsScore = 0;


    accountingKeywords.forEach(keyword => {

        if (text.includes(keyword.toLowerCase())) {
            accountingScore++;
        }

    });


    economicsKeywords.forEach(keyword => {

        if (text.includes(keyword.toLowerCase())) {
            economicsScore++;
        }

    });


    mathematicsKeywords.forEach(keyword => {

        if (text.includes(keyword.toLowerCase())) {
            mathematicsScore++;
        }

    });


    const highestScore = Math.max(
        accountingScore,
        economicsScore,
        mathematicsScore
    );


    if (highestScore === 0) {
        return null;
    }


    if (accountingScore === highestScore) {
        return "Accounting";
    }


    if (economicsScore === highestScore) {
        return "Economics";
    }


    return "Mathematics";
}


// ============================================================
// SEARCH KNOWLEDGE
// ============================================================

function searchKnowledge(question, knowledge) {

    const text = question.toLowerCase();

    let bestMatch = null;
    let bestScore = 0;


    knowledge.forEach(entry => {

        let score = 0;


        entry.keywords.forEach(keyword => {

            if (text.includes(keyword.toLowerCase())) {
                score += 5;
            }

        });


        const topicWords =
            entry.topic.toLowerCase().split(/\s+/);


        topicWords.forEach(word => {

            if (text.includes(word)) {
                score += 2;
            }

        });


        if (score > bestScore) {

            bestScore = score;
            bestMatch = entry;

        }

    });


    if (!bestMatch || bestScore === 0) {
        return null;
    }


    return bestMatch;
}


