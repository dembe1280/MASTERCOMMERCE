/* =========================================
   ANSWER QUESTION
========================================= */

function answerQuestion(question) {

    const cleanQuestion = question.trim();

    if (!cleanQuestion) {
        return;
    }

    if (isGreeting(cleanQuestion)) {

        addAssistantMessage(greetingAnswer());

        return;
    }

    if (isDeveloperQuestion(cleanQuestion)) {

        addAssistantMessage(developerAnswer());

        return;
    }

    const subject = detectSubject(cleanQuestion);

    if (!subject) {

        addAssistantMessage(
`I'm not completely sure which subject you mean.

Please mention Accounting, Economics or Mathematics, or ask your question more clearly.

For example:

"What is depreciation?"

"What is inflation?"

"Solve 2x + 5 = 15."`
        );

        return;
    }


    let result = null;


    if (subject === "Accounting") {

        result = searchKnowledge(
            cleanQuestion,
            accountingKnowledge
        );

        if (result) {

            addAssistantMessage(result.information);

        } else {

            addAssistantMessage(
`I understand that this is an Accounting question, but I don't have enough information in my current Accounting knowledge base to answer it properly yet.

Try asking about assets, liabilities, equity, revenue, expenses, inventory, VAT, financial statements, ratios, IFRS, auditing or another accounting topic.`
            );

        }

        return;
    }


    if (subject === "Economics") {

        result = searchKnowledge(
            cleanQuestion,
            economicsKnowledge
        );

        if (result) {

            addAssistantMessage(result.information);

        } else {

            addAssistantMessage(
`I understand that this is an Economics question, but I don't have enough information in my current Economics knowledge base to answer it properly yet.

Try asking about demand, supply, scarcity, opportunity cost, inflation, unemployment, GDP, fiscal policy, monetary policy or elasticity.`
            );

        }

        return;
    }


    if (subject === "Mathematics") {

        result = searchKnowledge(
            cleanQuestion,
            mathematicsKnowledge
        );

        if (result) {

            addAssistantMessage(result.information);

        } else {

            addAssistantMessage(
`I understand that this is a Mathematics question, but I don't have enough information in my current Mathematics knowledge base to answer it properly yet.

Try asking about algebra, equations, quadratics, sequences, functions, trigonometry, statistics, probability, financial mathematics, differentiation or integration.`
            );

        }

        return;
    }

}


